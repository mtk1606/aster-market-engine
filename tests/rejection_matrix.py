"""Known-invalid ITCH sessions should fail in both implementations.

The two programs share intended protocol invariants but not their decoder or
order-book code. This matrix uses generated bytes, not a captured Nasdaq feed.
"""
import os
from pathlib import Path
import subprocess
import sys
import tempfile

from crosscheck import frame

BINARY = Path(os.environ["ASTER_BINARY"]).resolve()
REFERENCE = Path(__file__).resolve().parents[1] / "tools" / "reference_replay.py"


def make_scenarios():
    start = frame("S", stamp=1, code="O")
    directory = frame("R", locate=7, stock="TEST", stamp=2)
    add = frame("A", locate=7, order=77, shares=20, stamp=3)
    close = frame("S", stamp=5, code="C")
    good = start + directory + add + close
    payloads = {"valid": good,
                "valid_terminator": good + b"\0\0",
                "missing_close": start + directory + add,
                "duplicate_directory": start + directory + directory + add + close,
                "duplicate_order": start + directory + add + add + close,
                "unknown_order": start + directory + frame("E", locate=7, order=99, shares=1, stamp=4) + close,
                "excess_cancel": start + directory + add + frame("X", locate=7, order=77, shares=21, stamp=4) + close,
                "wrong_locate": start + directory + add + frame("D", locate=8, order=77, stamp=4) + close,
                "timestamp_regression": start + directory + add + frame("S", stamp=2, code="C"),
                "message_after_close": good + frame("D", locate=7, order=77, stamp=6),
                "unknown_system_code": start + frame("S", stamp=2, code="Z") + directory + add + close,
                "late_open": directory + start + add + close,
                "bad_symbol": start + directory + frame("A", locate=7, order=77, stock="MISMATCH", stamp=3) + close,
                "empty_terminator_middle": start + directory + b"\0\0" + add + close,
                "trailing_bytes": good + b"\x01",
                "unknown_type": start + directory + b"\x00\x0cZ" + bytes(11) + close,
                "bad_length": start + directory + b"\x00\x0b" + add[2:] + close,
                "truncated_payload": good[:-4],
                "truncated_prefix": good + b"\x00",
                "zero_price": start + directory + frame("A", locate=7, order=77, price=0, stamp=3) + close,
                "zero_shares": start + directory + frame("A", locate=7, order=77, shares=0, stamp=3) + close,
                "zero_order": start + directory + frame("A", locate=7, order=0, stamp=3) + close}
    wrong_side = bytearray(add)
    wrong_side[2+19] = ord("?")
    payloads["invalid_side"] = start + directory + bytes(wrong_side) + close
    return payloads


def invoke(command):
    return subprocess.run(command, capture_output=True, text=True)


def main():
    cases = make_scenarios()
    with tempfile.TemporaryDirectory() as temporary:
        source = Path(temporary) / "session.itch"
        for name, content in cases.items():
            source.write_bytes(content)
            expected_success = name.startswith("valid")
            for method in ("mmap", "read"):
                cmd = [str(BINARY), str(source), "--complete", "--validate",
                       "--io", method]
                if method == "read":
                    cmd += ["--chunk", "3"]
                result = invoke(cmd)
                if (result.returncode == 0) != expected_success:
                    raise AssertionError(f"{name} {method}: unexpected status: {result.stdout} {result.stderr}")
            reference = invoke([sys.executable, str(REFERENCE), str(source), "--interval", "2"])
            if (reference.returncode == 0) != expected_success:
                raise AssertionError(f"{name} python: unexpected status: {reference.stdout} {reference.stderr}")
    print(f"rejection matrix passed: {len(cases) - 2} invalid and 2 valid fixtures across three paths")


if __name__ == "__main__":
    main()
